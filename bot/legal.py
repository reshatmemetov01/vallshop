def _tg_contact(config) -> str:
    c = (getattr(config, "support_contact", None) or "").strip()
    if c.startswith("@"):
        return f"<a href='https://t.me/{html.escape(c[1:])}'>{html.escape(c)}</a>"
    if c.startswith("http"):
        return f"<a href='{html.escape(c)}'>{html.escape(c)}</a>"
    if c:
        return html.escape(c)
    return "служба поддержки VallShop"


